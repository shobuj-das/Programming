# ============================================================
# Day 21 - Longest Substring Without Repeating Characters
#
# Difficulty:
# Medium
#
# Concepts:
# - String
# - Sliding Window
# - Dictionary / Set
# - Two Pointers
#
# ------------------------------------------------------------
#
# Problem Statement
#
# Given a string, find the length of the longest substring
# without repeating characters.
#
# A substring consists of consecutive characters.
#
# Return ONLY the maximum length.
#
# ------------------------------------------------------------
#
# Examples
#
# Input:
# "abcabcbb"
#
# Output:
# 3
#
# Explanation:
# "abc"
#
# ------------------------------------------------------------
#
# Input:
# "bbbbb"
#
# Output:
# 1
#
# Explanation:
# "b"
#
# ------------------------------------------------------------
#
# Input:
# "pwwkew"
#
# Output:
# 3
#
# Explanation:
# "wke"
#
# ------------------------------------------------------------
#
# Input:
# ""
#
# Output:
# 0
#
# ------------------------------------------------------------
#
# Input:
# "dvdf"
#
# Output:
# 3
#
# Explanation:
# "vdf"
#
# ------------------------------------------------------------
#
# Constraints
#
# - String may contain:
#   - lowercase letters
#   - uppercase letters
#   - digits
#   - symbols
#   - spaces
#
# ------------------------------------------------------------
#
# Follow-up
#
# 1. Solve using a brute-force approach.
#
# 2. Then optimize it using Sliding Window.
#
# 3. Compare the time complexity of both approaches.
#
